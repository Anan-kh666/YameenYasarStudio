// Runs automatically after `npm run build` (the "postbuild" npm hook).
//
// Writes out/_headers, the file Cloudflare (Pages and Workers static
// assets) reads to add HTTP response headers. A static export can't set
// headers from next.config, so this is where the site's security headers
// live.
//
// The Content-Security-Policy allows scripts only from our own origin plus
// the exact inline scripts Next.js put in each page, by their SHA-256
// hash. Any other inline script (an injected <script>, an onclick=...)
// is refused by the browser. The hashes change on every build, which is
// why this runs at build time instead of being a hand-written file.
//
// It also removes macOS .DS_Store files, which Finder drops into public/
// and which would otherwise be deployed (they list folder contents).

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile, rm } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const OUT = "out";

/* Origins the pages legitimately talk to. Keep this list short. */
const WEB3FORMS = "https://api.web3forms.com"; // contact form POST (Contact.tsx)
// Cloudflare Web Analytics, in case it's switched on in the dashboard:
// Cloudflare then injects its beacon script into every page.
const CF_BEACON_SCRIPT = "https://static.cloudflareinsights.com";
const CF_BEACON_CONNECT = "https://cloudflareinsights.com";

/* Headers for every response */
const COMMON = {
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "X-Frame-Options": "DENY",
  "Cross-Origin-Opener-Policy": "same-origin",
  "Permissions-Policy":
    "camera=(), microphone=(), geolocation=(), payment=(), usb=(), serial=(), bluetooth=(), " +
    "magnetometer=(), gyroscope=(), accelerometer=(), browsing-topics=()",
  // One year of HTTPS-only. No includeSubDomains/preload on purpose: that
  // would also force every other subdomain of the domain onto HTTPS forever.
  "Strict-Transport-Security": "max-age=31536000",
};

async function walk(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(path)));
    else files.push(path);
  }
  return files;
}

/* SHA-256 of every inline script the browser would execute. JSON-LD
   (type="application/ld+json") is data, not code, so CSP ignores it. */
function inlineScriptHashes(html) {
  const hashes = new Set();
  for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    if (/\bsrc\s*=/i.test(attrs)) continue;
    const type = attrs.match(/\btype\s*=\s*["']?([^"'\s>]+)/i)?.[1]?.toLowerCase();
    if (type && !["text/javascript", "module", "application/javascript"].includes(type)) continue;
    hashes.add(`'sha256-${createHash("sha256").update(body, "utf8").digest("base64")}'`);
  }
  return [...hashes];
}

function csp(hashes) {
  return [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(" ")} ${CF_BEACON_SCRIPT}`,
    // Inline style attributes (CSS variables, animation delays) and
    // next/font's <style> need this; styles can't run code.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    "media-src 'self'",
    `connect-src 'self' ${WEB3FORMS} ${CF_BEACON_CONNECT}`,
    `form-action 'self' ${WEB3FORMS}`,
    "frame-src 'none'",
    "frame-ancestors 'none'",
    "object-src 'none'",
    "base-uri 'self'",
    "manifest-src 'self'",
    "worker-src 'self'",
    "upgrade-insecure-requests",
  ].join("; ");
}

/* out/ar/index.html → ["/ar/", "/ar/index.html"]; out/404.html → ["/404.html"] */
function urlPaths(file) {
  const rel = "/" + relative(OUT, file).split(sep).join("/");
  if (rel === "/index.html") return ["/", "/index.html"];
  if (rel.endsWith("/index.html")) return [rel.slice(0, -"index.html".length), rel];
  return [rel];
}

const files = await walk(OUT);

let removed = 0;
for (const f of files) {
  if (f.endsWith(".DS_Store")) {
    await rm(f);
    removed++;
  }
}

const lines = [
  "# Generated by scripts/security-headers.mjs during `npm run build`. Do not edit by hand.",
  "",
  "/*",
  ...Object.entries(COMMON).map(([k, v]) => `  ${k}: ${v}`),
  "",
];

let pages = 0;
for (const f of files.filter((f) => f.endsWith(".html")).sort()) {
  const hashes = inlineScriptHashes(await readFile(f, "utf8"));
  const value = csp(hashes);
  // Cloudflare's limit for a single header line in _headers.
  if (value.length > 2000) throw new Error(`CSP for ${f} is ${value.length} chars (limit 2000)`);
  for (const path of urlPaths(f)) lines.push(path, `  Content-Security-Policy: ${value}`, "");
  pages++;
}

await writeFile(join(OUT, "_headers"), lines.join("\n"));
console.log(`security-headers: CSP for ${pages} pages written to ${OUT}/_headers` + (removed ? `, removed ${removed} .DS_Store` : ""));
